/**
 * Generate metadata for user profile pages
 */
export function createUserProfileMetadata(user: {
  username: string;
  displayName?: string;
  bio?: string;
  generationCount?: number;
}): Metadata {
  const name = user.displayName || user.username;
  const description =
    user.bio ||
    `View Claude Code prompts created by ${name}. ${user.generationCount || 0} custom prompts.`;

  return createMetadata({
    type: "user-profile",
    title: name,
    description,
    path: `/u/${user.username}`,
    noIndex: (user.generationCount || 0) < 3, // Don't index profiles with few generations
  });
}

/**
 * Generate metadata for generation pages
 */
export function createGenerationMetadata(generation: {
  title: string;
  slug: string;
  description?: string;
  content?: string;
  authorName?: string;
}): Metadata {
  const description =
    generation.description ||
    cleanDescription(generation.content || "", 155) ||
    "Custom Claude Code sub-agent prompt generated by the community.";

  return createMetadata({
    type: "generation",
    title: generation.title,
    description,
    path: `/g/${generation.slug}`,
    author: generation.authorName,
    noIndex: !generation.description && !generation.content, // Don't index empty generations
  });
}

/**
 * Clean description text for meta tags
 */
function cleanDescription(content: string, maxLength = 155): string {
  return content
    .replace(/```[\s\S]*?```/g, "")
    .replace(/`[^`]+`/g, "")
    .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
    .replace(/[#*_~>-]/g, "")
    .replace(/\n+/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, maxLength);
}
