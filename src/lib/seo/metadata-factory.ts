/**
 * Generate full canonical URL
 */
export function getCanonicalUrl(path: string): string {
  const cleanPath = path.startsWith("/") ? path : `/${path}`;
  return `${BASE_URL}${cleanPath}`;
}

/**
 * Generate OG image URL with dynamic parameters
 */
export function getOgImageUrl(path: string, _config?: { title?: string; type?: PageType }): string {
  // For dynamic OG images, use the path-based route
  if (path === "/" || path === "") {
    return `${BASE_URL}/cover-image.png`;
  }
  // For pages with dynamic OG images
  return `${BASE_URL}${path}/opengraph-image`;
}

/**
 * Create complete metadata object for any page type
 */
export function createMetadata(config: MetadataConfig): Metadata {
  const {
    type,
    title,
    description,
    path,
    keywords = [],
    noIndex = false,
    publishedTime,
    modifiedTime,
    image,
    author = SEO_CONFIG.siteName,
    section,
  } = config;

  const processedTitle = TITLE_TEMPLATES[type](title);
  const processedDescription = DESCRIPTION_TEMPLATES[type](description, title);
  const canonicalUrl = getCanonicalUrl(path);
  const ogImageUrl = image?.url || getOgImageUrl(path, { title, type });

  // Base keywords always included
  const baseKeywords = ["Claude Code", "sub-agents", "AI prompts", "Anthropic"];
  const allKeywords = [...new Set([...baseKeywords, ...keywords])];

  const metadata: Metadata = {
    title: processedTitle,
    description: processedDescription,
    keywords: allKeywords,
    authors: [{ name: author }],
    creator: SEO_CONFIG.siteName,
    publisher: SEO_CONFIG.siteName,
    alternates: {
      canonical: canonicalUrl,
    },
    robots: noIndex
      ? { index: false, follow: true }
      : {
          index: true,
          follow: true,
          googleBot: {
            index: true,
            follow: true,
            "max-video-preview": -1,
            "max-image-preview": "large",
            "max-snippet": 160,
          },
        },
    openGraph: {
      title: processedTitle,
      description: processedDescription,
      url: canonicalUrl,
      siteName: SEO_CONFIG.siteName,
      locale: SEO_CONFIG.locale,
      type: getOgType(type),
      images: [
        {
          url: ogImageUrl,
          width: image?.width || 1200,
          height: image?.height || 630,
          alt: image?.alt || processedTitle,
        },
      ],
      ...(publishedTime && { publishedTime }),
      ...(modifiedTime && { modifiedTime }),
      ...(author && { authors: [author] }),
    },
    twitter: {
      card: "summary_large_image",
      title: processedTitle,
      description: processedDescription,
      images: [ogImageUrl],
    },
  };

  // Add article-specific metadata
  if (isArticleType(type) && section) {
    (metadata.openGraph as Record<string, unknown>).section = section;
  }

  return metadata;
}

/**
 * Determine OG type based on page type
 */
function getOgType(type: PageType): "website" | "article" | "profile" {
  const articleTypes: PageType[] = ["rule", "tutorial", "guide", "comparison", "generation"];
  const profileTypes: PageType[] = ["user-profile"];

  if (articleTypes.includes(type)) return "article";
  if (profileTypes.includes(type)) return "profile";
  return "website";
}

/**
 * Check if page type should have article metadata
 */
function isArticleType(type: PageType): boolean {
  return ["rule", "tutorial", "guide", "comparison", "generation"].includes(type);
}

/**
 * Generate metadata for rule pages
 */
export function createRuleMetadata(rule: {
  title: string;
  slug: string;
  description?: string;
  content?: string;
  tags?: string[];
  libs?: string[];
}): Metadata {
  const description = rule.description || cleanDescription(rule.content || "", 155);

  return createMetadata({
    type: "rule",
    title: rule.title,
    description,
    path: `/${rule.slug}`,
    keywords: [...(rule.tags || []), ...(rule.libs || [])],
    section: rule.tags?.[0],
    publishedTime: "2024-01-01T00:00:00Z",
    modifiedTime: new Date().toISOString(),
  });
}

/**
 * Generate metadata for category pages
 */
export function createCategoryMetadata(category: {
  name: string;
  slug: string;
  description: string;
  keywords?: string[];
  count: number;
}): Metadata {
  return createMetadata({
    type: "category",
    title: category.name,
    description: category.description,
    path: `/agents/${category.slug}`,
    keywords: category.keywords || [],
  });
}

