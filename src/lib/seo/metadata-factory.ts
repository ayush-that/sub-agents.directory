/**
 * Generate metadata for comparison pages
 */
export function createComparisonMetadata(comparison: {
  rule1: { title: string; slug: string };
  rule2: { title: string; slug: string };
  description?: string;
}): Metadata {
  const title = `${comparison.rule1.title} vs ${comparison.rule2.title}: Which Claude Code Agent to Use?`;
  const description =
    comparison.description ||
    `Compare ${comparison.rule1.title} and ${comparison.rule2.title} Claude Code sub-agents. Find out which is best for your project.`;

  return createMetadata({
    type: "comparison",
    title,
    description,
    path: `/agents/compare/${comparison.rule1.slug}-vs-${comparison.rule2.slug}`,
    keywords: [comparison.rule1.title, comparison.rule2.title, "comparison"],
  });
}

