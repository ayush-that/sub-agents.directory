/**
 * Metadata Factory
 * Centralized metadata generation for consistent SEO across 100K+ pages
 * Prevents duplication, keyword cannibalization, and thin content
 */

import type { Metadata } from "next";
import { SEO_CONFIG, BASE_URL, type PageType } from "./constants";

/**
 * Base configuration for metadata generation
 */
export interface MetadataConfig {
  /** Page type for determining template and schema */
  type: PageType;
  /** Primary title - will be templated based on page type */
  title: string;
  /** Meta description - should be unique and 150-160 chars */
  description: string;
  /** URL path (without base URL) */
  path: string;
  /** Additional keywords for the page */
  keywords?: string[];
  /** Whether to noindex this page */
  noIndex?: boolean;
  /** Published date (ISO string) */
  publishedTime?: string;
  /** Modified date (ISO string) */
  modifiedTime?: string;
  /** Custom OG image configuration */
  image?: {
    url: string;
    alt: string;
    width?: number;
    height?: number;
  };
  /** Author information */
  author?: string;
  /** Section/category the content belongs to */
  section?: string;
}

